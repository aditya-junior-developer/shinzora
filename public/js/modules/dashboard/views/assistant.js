/* ==========================================================================
   Shinzora — AI Assistant
   A real conversation against the server-side Gemini proxy. Conversations and
   messages are persisted in Postgres; the browser never sees an API key.
   ========================================================================== */

import { qs, esc, on, safeSet } from "../../../lib/dom.js";
import { icon } from "../../../lib/icons.js";
import { timeAgo } from "../../../lib/format.js";
import { state, aiCredits, plan } from "../../../lib/store.js";
import { sb, normalizeError, getSession } from "../../../lib/supabase.js";
import { actionPendingDeploy, api, runtimeConfig } from "../../../lib/api.js";
import { pageHead, emptyState, setupNotice } from "../components.js";
import { toast, toastError } from "../../../ui/toast.js";
import { confirmDialog, formDialog } from "../../../ui/modal.js";

const SUGGESTIONS = [
  "What should my homepage say for a premium fashion label?",
  "Write three Instagram captions for a new ceramic collection.",
  "Review my pricing: 15 products, average order ₹2,400, 22% margin.",
  "Draft a 4-week launch plan for a skincare brand in India.",
  "Which pages does a service business website actually need?"
];

let conversationId = null;

/* How long the assistant may sit silent before the UI says something.
   The reply is written to Postgres before the function answers, so a request
   that runs long has still produced an answer — the client just has not seen
   it. That is exactly the state the screenshots came from: three dots spinning
   for half an hour while `ai_messages` already held the reply. Generous on
   purpose: 99th percentile here is about 90 seconds. */
const ANSWER_WAIT_MS = 100000;
const ANSWER_NUDGE_MS = 12000;

export default async function render(root, ctx) {
  const config = await runtimeConfig();
  const aiReady = Boolean(config?.ai?.configured);

  root.innerHTML = `
    ${pageHead({
      title: "AI Assistant",
      desc: "Ask about strategy, copy, pricing, operations — the assistant sees your business profile as context.",
      actions: `<button class="btn btn-secondary btn-sm" id="new-chat">${icon("plus", { size: 14 })}New conversation</button>
                <span class="badge badge-violet">${icon("sparkles", { size: 11 })}${esc(plan().name)} · ${aiCredits().used}/${aiCredits().limit}</span>`
    })}
    ${!aiReady ? setupNotice({ code: "ai_unconfigured", message: "The AI service is not configured on this deployment.", hint: config?.ai?.key_env ? `Set ${config.ai.key_env} on the server — in .env for a local deployment, or in the project's environment variables — then reload this page. Nothing is simulated while it is missing.` : "Set the AI provider key on the server, then reload this page." }, "The assistant") : ""}
    ${commandBar()}
    <div class="chat-shell">
      <div class="chat-head">
        <span class="avatar avatar-sm" style="background:linear-gradient(150deg,#a855f7,#4c1d95)">${icon("sparkles", { size: 13 })}</span>
        <div>
          <div style="font-size:var(--fs-sm);font-weight:600;color:#fff">Shinzora Assistant</div>
          <div class="chat-model">${aiReady ? "Gemini · server-side · conversation saved" : "Offline — service not configured"}</div>
        </div>
        <button class="btn btn-ghost btn-sm" id="history-toggle" style="margin-left:auto">${icon("clock", { size: 14 })}History</button>
      </div>

      <div class="chat-log" id="chat-log">
        ${emptyState({
          icon: "sparkles",
          title: "Ask anything about the business",
          desc: "The assistant answers with your business name, category and goals in context. Every exchange is saved to your account."
        })}
      </div>

      <div class="chat-suggestions" id="chat-suggestions">
        ${SUGGESTIONS.slice(0, 3)
          .map((text) => `<button class="chip" data-suggest="${esc(text)}">${esc(text)}</button>`)
          .join("")}
      </div>

      <div class="chat-composer">
        <div class="composer-box">
          <textarea id="chat-input" rows="1" placeholder="${aiReady ? "Ask the assistant…" : "AI service not configured"}" ${aiReady ? "" : "disabled"} aria-label="Message"></textarea>
          <button class="btn btn-primary btn-sm btn-icon" id="chat-send" ${aiReady ? "" : "disabled"} aria-label="Send message">
            ${icon("send", { size: 15 })}
          </button>
        </div>
        <div class="composer-foot">
          <span>Enter to send · Shift + Enter for a new line</span>
          <span>Responses are generated by AI — verify anything financial or legal.</span>
        </div>
      </div>
    </div>

    <div class="card" id="history-panel" hidden style="margin-top:var(--s-4)">
      <div class="card-head">
        <div class="card-title">Conversations</div>
        <div class="field" style="margin:0;max-width:240px">
          <input class="input input-sm" id="history-search" type="search" placeholder="Search titles" aria-label="Search conversations" />
        </div>
      </div>
      <div class="card-body" id="history-list"><p class="muted" style="font-size:var(--fs-xs)">Loading…</p></div>
    </div>`;

  const log = qs("#chat-log");
  const input = qs("#chat-input");
  const send = qs("#chat-send");

  const scrollDown = () => {
    log.scrollTop = log.scrollHeight;
  };

  /* ==========================================================================
     Commands
     --------------------------------------------------------------------------
     The chat is a conversation; this is the part that changes something. The
     model's only job is to turn one sentence into one action from a closed list;
     the owner confirms, and the write happens in Postgres. A proposal that the
     model gets wrong costs a click, never a wrong row.
     ====================================================================== */
  const commandState = { busy: false };

  function commandBar() {
    return `<div class="card" id="command-card" style="margin-bottom:var(--s-3)">
      <div class="card-body" style="padding:var(--s-3)">
        <div class="row gap-2 wrap" style="align-items:center">
          <span class="badge badge-violet">${icon("zap", { size: 11 })}Do something</span>
          <input class="input grow" id="command-input" placeholder="Add a Product: cotton tote, ₹450, 20 in stock" aria-label="Tell the assistant what to do" />
          <button class="btn btn-primary btn-sm" id="command-run" ${aiReady ? "" : "disabled"}>Run</button>
        </div>
        <div class="dim" style="font-size:var(--fs-2xs);margin-top:6px">
          It can create a product, change stock, move an order's status or add a customer. It shows you what it will do before it does it.
        </div>
        <div id="command-preview"></div>
      </div>
    </div>`;
  }

  async function runCommand(text) {
    const request = String(text || "").trim();
    if (!request || commandState.busy || !aiReady) return;
    commandState.busy = true;
    const preview = qs("#command-preview");
    const button = qs("#command-run");
    button.disabled = true;
    preview.innerHTML = `<div class="dim" style="font-size:var(--fs-xs);margin-top:var(--s-3)">Working out what to do…</div>`;

    try {
      /* Only names and ids go to the model — never an email address or a
         customer note. It needs enough to pick the right row, not more. */
      const [{ data: products }, { data: openOrders }] = await Promise.all([
        sb.from("store_products").select("id, name, stock, price").order("created_at", { ascending: false }).limit(40),
        sb.from("store_orders").select("id, order_number, status, customer_name").order("created_at", { ascending: false }).limit(20)
      ]);

      const proposal = await api.ai.command({
        request,
        context: {
          products: (products || []).map((row) => ({ id: row.id, name: row.name, stock: row.stock, price: row.price })),
          orders: (openOrders || []).map((row) => ({ id: row.id, number: row.order_number, status: row.status, customer: row.customer_name })),
          business: state.business?.name || null
        }
      });

      if (!proposal?.understood) {
        preview.innerHTML = `<div class="alert alert-warn" style="margin-top:var(--s-3);font-size:var(--fs-xs)">${icon("info", { size: 14 })}
          <div>${esc(proposal?.summary || "I could not turn that into something I can run.")}${
            (proposal?.missing || []).length ? `<br>Missing: ${proposal.missing.map((row) => esc(row)).join(", ")}` : ""
          }</div></div>`;
        return;
      }

      preview.innerHTML = `<div class="command-proposal">
        <div class="row between gap-2" style="align-items:baseline">
          <strong style="font-size:var(--fs-sm)">${esc(proposal.summary || proposal.action)}</strong>
          <span class="badge badge-neutral">${esc(proposal.action)}</span>
        </div>
        <pre class="command-payload">${esc(JSON.stringify(proposal.payload || {}, null, 2))}</pre>
        <div class="row gap-2">
          <button class="btn btn-primary btn-sm" id="command-confirm">${icon("check", { size: 13 })}Confirm</button>
          <button class="btn btn-ghost btn-sm" id="command-cancel">Cancel</button>
        </div>
      </div>`;

      qs("#command-cancel").addEventListener("click", () => {
        preview.innerHTML = "";
        qs("#command-input").value = "";
      });

      qs("#command-confirm").addEventListener("click", async (event) => {
        event.currentTarget.disabled = true;
        try {
          const { data, error } = await sb.rpc("assistant_command_apply", {
            p_action: proposal.action,
            p_payload: proposal.payload || {},
            p_command: null
          });
          if (error) throw normalizeError(error);
          preview.innerHTML = `<div class="alert alert-ok" style="margin-top:var(--s-3);font-size:var(--fs-xs)">${icon("check", { size: 14 })}
            <div>Done — ${esc(proposal.summary || proposal.action)}.</div></div>`;
          qs("#command-input").value = "";
          bubble("ai", `Done: ${proposal.summary || proposal.action}.`, "command");
          if (data?.productId) toast({ title: "Added to your catalogue" }, { tone: "success" });
        } catch (error) {
          preview.innerHTML = `<div class="alert alert-danger" style="margin-top:var(--s-3);font-size:var(--fs-xs)">${icon("triangle-alert", { size: 14 })}
            <div>${esc(normalizeError(error).message)}</div></div>`;
        }
      });
    } catch (error) {
      preview.innerHTML = actionPendingDeploy(error)
        ? `<div class="alert alert-warn" style="margin-top:var(--s-3);font-size:var(--fs-xs)">${icon("info", { size: 14 })}
            <div>Running commands needs the updated <code>ai</code> Edge Function, which is not deployed on this instance yet.
            The chat still works; nothing was changed in your store.</div></div>`
        : `<div class="alert alert-danger" style="margin-top:var(--s-3);font-size:var(--fs-xs)">${icon("triangle-alert", { size: 14 })}
            <div>${esc(normalizeError(error).message)}</div></div>`;
    } finally {
      commandState.busy = false;
      button.disabled = false;
    }
  }

  const bubble = (role, content, meta = "") => {
    const wrap = document.createElement("div");
    wrap.className = `msg ${role === "user" ? "msg-user" : "msg-ai"}`;
    wrap.innerHTML = `
      <span class="msg-avatar">${role === "user" ? esc((state.profile?.full_name || "You").slice(0, 2).toUpperCase()) : icon("sparkles", { size: 14 })}</span>
      <div>
        <div class="msg-bubble">${formatContent(content)}</div>
        ${meta ? `<div class="msg-meta">${esc(meta)}</div>` : ""}
      </div>`;
    log.append(wrap);
    scrollDown();
    return wrap;
  };

  /**
   * The waiting bubble.
   *
   * It counts, so a slow answer is visibly alive rather than indistinguishable
   * from a hung page, and it offers a way out: `cancel()` stops waiting without
   * throwing anything away — whatever the server ends up saving is picked up by
   * `recoverReply()`.
   */
  const thinking = () => {
    const wrap = document.createElement("div");
    wrap.className = "msg msg-ai";
    wrap.setAttribute("data-thinking", "");
    wrap.innerHTML = `<span class="msg-avatar">${icon("sparkles", { size: 14 })}</span>
      <div class="msg-bubble">
        <span class="typing"><i></i><i></i><i></i></span>
        <span class="thinking-note" data-thinking-note></span>
        <button class="btn btn-ghost btn-sm thinking-cancel" type="button" data-thinking-cancel hidden>Stop waiting</button>
      </div>`;
    log.append(wrap);
    scrollDown();

    const note = wrap.querySelector("[data-thinking-note]");
    const cancelButton = wrap.querySelector("[data-thinking-cancel]");
    const started = Date.now();
    const tick = setInterval(() => {
      const seconds = Math.round((Date.now() - started) / 1000);
      if (note) note.textContent = seconds >= 2 ? `${Math.floor(seconds / 60)}:${String(seconds % 60).padStart(2, "0")}` : "";
      if (cancelButton && seconds >= ANSWER_NUDGE_MS / 1000) cancelButton.hidden = false;
    }, 1000);
    if (typeof tick?.unref === "function") tick.unref();

    /* `cancelled` resolves when the person presses Stop, so the send can stop
       waiting immediately instead of waiting out the full clock. */
    const cancelled = new Promise((resolve) => {
      cancelButton?.addEventListener("click", () => {
        clearInterval(tick);
        if (note) note.textContent = "Stopped waiting — checking what was saved.";
        resolve({ __cancelled: true });
      });
    });

    wrap.stop = () => clearInterval(tick);
    wrap.cancelled = cancelled;
    return wrap;
  };

  async function loadLatestConversation() {
    try {
      const session = await getSession();
      if (!session) return;
      const { data } = await sb
        .from("ai_conversations")
        .select("id, title, updated_at, user_id")
        .eq("user_id", session.user.id)
        .eq("kind", "assistant")
        .order("updated_at", { ascending: false })
        .limit(1)
        .maybeSingle();
      if (!data) return;
      conversationId = data.id;
      const { data: rows } = await sb
        .from("ai_messages")
        .select("*")
        .eq("conversation_id", data.id)
        .order("created_at", { ascending: true })
        .limit(60);
      if (rows?.length) {
        log.innerHTML = "";
        rows.forEach((row) => bubble(row.role === "user" ? "user" : "ai", row.content, timeAgo(row.created_at)));
      }
    } catch (error) {
      if (normalizeError(error).code !== "schema_missing") console.warn(error);
    }
  }

  /* Opening a conversation is one operation, whether it came from the History
     panel, the sidebar's recent list, or a ?conversation= link that survived a
     reload. It keeps the URL in step so the sidebar can mark the right chat and
     so a refresh lands back where the user was. */
  async function openConversation(id, { updateUrl = true } = {}) {
    conversationId = id;
    if (log.querySelector(".empty") || log.querySelector(".msg")) log.innerHTML = "";
    log.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">Loading conversation…</p>`;
    try {
      const { data, error } = await sb
        .from("ai_messages")
        .select("role, content, created_at")
        .eq("conversation_id", id)
        .order("created_at", { ascending: true });
      if (error) throw error;
      log.innerHTML = "";
      (data || []).forEach((row) => bubble(row.role === "user" ? "user" : "ai", row.content, timeAgo(row.created_at)));
      if (!data?.length) {
        log.innerHTML = emptyState({ icon: "message-square", title: "This conversation is empty", desc: "Send a message to start it." });
      }
      scrollDown();
      if (updateUrl) {
        const url = `/app/?view=assistant&conversation=${encodeURIComponent(id)}`;
        history.replaceState({ view: "assistant" }, "", url);
      }
      window.dispatchEvent(new CustomEvent("shinzora:chats-changed", { detail: { conversationId: id } }));
      return true;
    } catch (error) {
      log.innerHTML = emptyState({ icon: "circle-alert", title: "That conversation could not be opened", desc: normalizeError(error).message });
      toastError(normalizeError(error));
      return false;
    }
  }

  /** A fresh conversation: nothing saved until the first message is sent. */
  function startNewConversation({ updateUrl = true } = {}) {
    conversationId = null;
    log.innerHTML = emptyState({
      icon: "sparkles",
      title: "New conversation",
      desc: "Ask anything about the business. Context is carried automatically."
    });
    safeSet("#chat-suggestions", SUGGESTIONS.slice(0, 3)
      .map((text) => `<button class="chip" data-suggest="${esc(text)}">${esc(text)}</button>`)
      .join(""));
    if (updateUrl) history.replaceState({ view: "assistant" }, "", "/app/?view=assistant&new=1");
    input.focus();
  }

  /**
   * Read back what the server actually saved.
   *
   * Called when the request failed, timed out, or was cancelled. The function
   * writes the answer to `ai_messages` before it responds, so a lost response
   * is not a lost answer — it is an answer the page never painted. Without this
   * the only cure was a reload, which is why the assistant looked dead while the
   * database had already replied.
   */
  async function recoverReply({ sentAt, pending }) {
    try {
      const session = await getSession();
      if (!session) return false;

      /* `ai_messages` has no user column — it belongs to a conversation, and the
         conversation belongs to the user. So the conversation is resolved first:
         the one on screen, or the user's newest one when the very first message
         was the one that went quiet. */
      let target = conversationId;
      if (!target) {
        const { data: latest } = await sb
          .from("ai_conversations")
          .select("id")
          .eq("user_id", session.user.id)
          .eq("kind", "assistant")
          .order("updated_at", { ascending: false })
          .limit(1)
          .maybeSingle();
        target = latest?.id || null;
      }
      if (!target) return false;

      const { data } = await sb
        .from("ai_messages")
        .select("conversation_id, role, content, created_at")
        .eq("conversation_id", target)
        .eq("role", "assistant")
        .order("created_at", { ascending: false })
        .limit(1);

      const row = data?.[0];
      if (!row || new Date(row.created_at).getTime() < sentAt) return false;

      pending?.stop?.();
      pending?.remove();
      conversationId = row.conversation_id || target;
      bubble("ai", row.content, "saved on the server while this page was waiting");
      history.replaceState(
        { view: "assistant" },
        "",
        `/app/?view=assistant&conversation=${encodeURIComponent(conversationId)}`
      );
      window.dispatchEvent(new CustomEvent("shinzora:chats-changed", { detail: { conversationId } }));
      return true;
    } catch {
      return false;
    }
  }

  async function sendMessage(text) {
    const message = String(text || "").trim();
    if (!message || !aiReady) return;
    if (log.querySelector(".empty")) log.innerHTML = "";
    safeSet("#chat-suggestions", "");

    bubble("user", message, "You");
    input.value = "";
    input.style.height = "auto";
    send.disabled = true;
    const pending = thinking();
    const sentAt = Date.now();

    /* The wait is bounded here, not by hope. A request that never settles used
       to leave the composer disabled and the dots turning for as long as the tab
       stayed open. Whichever finishes first wins: the answer, or the clock. */
    let timer = null;
    const clock = new Promise((resolve) => {
      timer = setTimeout(() => resolve({ __timeout: true }), ANSWER_WAIT_MS);
      if (typeof timer?.unref === "function") timer.unref();
    });

    try {
      const result = await Promise.race([
        pending.cancelled,
        api.ai.chat({
          message,
          conversationId,
          context: {
            business: state.business || null,
            plan: plan().id,
            goals: state.business?.goals || []
          }
        }),
        clock
      ]);

      pending.stop();
      if (result?.__timeout || result?.__cancelled) {
        /* Not an error yet: the server may have saved the answer already. */
        const recovered = await recoverReply({ sentAt, pending });
        if (!recovered) {
          pending.remove();
          bubble(
            "ai",
            "That took longer than expected and nothing came back in time. Your message is saved — send it again, or reload and the answer will be in the conversation if it did arrive.",
            "timed out"
          );
          input.value = message;
        }
        return;
      }
      pending.remove();
      const wasNew = !conversationId;
      conversationId = result.conversationId || conversationId;
      bubble("ai", result.reply || "No response was returned.", `${result.model || "gemini"} · saved`);
      /* The first message creates the row, so that is when the URL and the
         sidebar's recent list can finally point at a real conversation. */
      if (conversationId && (wasNew || location.search.includes("new=1"))) {
        history.replaceState({ view: "assistant" }, "", `/app/?view=assistant&conversation=${encodeURIComponent(conversationId)}`);
        window.dispatchEvent(new CustomEvent("shinzora:chats-changed", { detail: { conversationId } }));
      }
      if (result.usage) {
        state.subscription = { ...(state.subscription || {}), ai_credits_used: result.usage.used };
        const badge = qs(".page-actions .badge");
        if (badge) badge.innerHTML = `${icon("sparkles", { size: 11 })}${esc(plan().name)} · ${result.usage.used}/${result.usage.limit}`;
      }
    } catch (error) {
      pending.stop?.();
      /* A failed request is not a lost answer: check before blaming the network. */
      if (await recoverReply({ sentAt, pending })) return;
      pending.remove();
      const normalized = normalizeError(error);
      if (normalized.code === "functions_unavailable") {
        bubble("ai", `The AI service is not deployed yet.\n\n${normalized.hint || ""}`, "setup required");
      } else {
        bubble("ai", `I could not complete that request.\n\n${normalized.message}${normalized.hint ? `\n\n${normalized.hint}` : ""}`, "error");
      }
      toastError(normalized);
    } finally {
      clearTimeout(timer);
      send.disabled = false;
      input.focus();
    }
  }

  /* ------------------------------------------------------------- listeners */
  on(send, "click", () => sendMessage(input.value));

  /* The command bar: Enter runs, Escape clears. Kept separate from the chat
     input so a question never accidentally becomes an action. */
  const commandInput = qs("#command-input");
  on(qs("#command-run"), "click", () => runCommand(commandInput.value));
  on(commandInput, "keydown", (event) => {
    if (event.key === "Enter") {
      event.preventDefault();
      void runCommand(commandInput.value);
    }
    if (event.key === "Escape") {
      commandInput.value = "";
      qs("#command-preview").innerHTML = "";
    }
  });
  on(input, "input", () => {
    input.style.height = "auto";
    input.style.height = `${Math.min(160, input.scrollHeight)}px`;
  });
  on(input, "keydown", (event) => {
    if (event.key === "Enter" && !event.shiftKey) {
      event.preventDefault();
      sendMessage(input.value);
    }
  });
  on(qs("#chat-suggestions"), "click", (event) => {
    const chip = event.target.closest("[data-suggest]");
    if (chip) sendMessage(chip.getAttribute("data-suggest"));
  });
  on(qs("#new-chat"), "click", () => startNewConversation());

  /* ------------------------------------------------------------- history */
  /* Conversations are the user's own record of what the assistant told them.
     The list can be searched, reopened, renamed and deleted, and every state is
     explicit: loading, empty, no matches, or an error with the real reason. */
  let historyRows = [];
  let historyQuery = "";

  function paintHistory() {
    const list = qs("#history-list");
    const term = historyQuery.trim().toLowerCase();
    const rows = term
      ? historyRows.filter((row) => String(row.title || "").toLowerCase().includes(term))
      : historyRows;

    if (!historyRows.length) {
      list.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">No saved conversations yet. Ask something and it is saved automatically.</p>`;
      return;
    }
    if (!rows.length) {
      list.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">No conversation title matches “${esc(historyQuery.trim())}”.</p>`;
      return;
    }

    list.innerHTML = `<div class="version-list">${rows
      .map(
        (row) => `<div class="version-item ${row.id === conversationId ? "is-current" : ""}">
            <button class="vi-main" data-conv="${esc(row.id)}" style="all:unset;display:flex;gap:var(--s-2);align-items:center;flex:1;cursor:pointer;min-width:0">
              <span class="vi-num">${icon("message-square", { size: 12 })}</span>
              <span class="truncate">${esc(row.title || "Untitled conversation")}</span>
            </button>
            <span class="vi-time">${esc(timeAgo(row.updated_at))}</span>
            <button class="btn btn-ghost btn-sm btn-icon" data-rename="${esc(row.id)}" title="Rename" aria-label="Rename conversation">${icon("pencil", { size: 13 })}</button>
            <button class="btn btn-ghost btn-sm btn-icon" data-delete="${esc(row.id)}" title="Delete" aria-label="Delete conversation">${icon("trash-2", { size: 13 })}</button>
          </div>`
      )
      .join("")}</div>`;
  }

  async function loadHistory() {
    const list = qs("#history-list");
    list.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">Loading conversations…</p>`;
    try {
      const session = await getSession();
      if (!session) throw new Error("Sign in again to load your conversations.");
      const { data, error } = await sb
        .from("ai_conversations")
        .select("id, title, updated_at, project_id")
        .eq("user_id", session.user.id)
        .eq("kind", "assistant")
        .order("updated_at", { ascending: false })
        .limit(100);
      if (error) throw error;
      historyRows = data || [];
      paintHistory();
    } catch (error) {
      historyRows = [];
      list.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">${esc(normalizeError(error).message)}</p>`;
    }
  }

  on(qs("#history-toggle"), "click", async () => {
    const panel = qs("#history-panel");
    panel.hidden = !panel.hidden;
    if (!panel.hidden) await loadHistory();
  });

  on(qs("#history-search"), "input", (event) => {
    historyQuery = event.target.value;
    paintHistory();
  });

  on(qs("#history-list"), "click", async (event) => {
    const renameButton = event.target.closest("[data-rename]");
    if (renameButton) {
      const id = renameButton.getAttribute("data-rename");
      const row = historyRows.find((entry) => entry.id === id);
      const values = await formDialog({
        title: "Rename conversation",
        desc: "A short, recognisable title makes the list easy to scan.",
        fields: [{ name: "title", label: "Title", value: row?.title || "", required: true, maxlength: 90 }],
        submitLabel: "Rename",
        size: "sm"
      });
      const next = values?.title;
      if (!next || !next.trim()) return;
      try {
        const { error } = await sb.from("ai_conversations").update({ title: next.trim().slice(0, 90) }).eq("id", id);
        if (error) throw error;
        historyRows = historyRows.map((entry) => (entry.id === id ? { ...entry, title: next.trim().slice(0, 90) } : entry));
        paintHistory();
        window.dispatchEvent(new CustomEvent("shinzora:chats-changed"));
        toast({ title: "Renamed" }, { tone: "success" });
      } catch (error) {
        toastError(normalizeError(error));
      }
      return;
    }

    const deleteButton = event.target.closest("[data-delete]");
    if (deleteButton) {
      const id = deleteButton.getAttribute("data-delete");
      const row = historyRows.find((entry) => entry.id === id);
      const ok = await confirmDialog({
        title: "Delete this conversation?",
        desc: `“${row?.title || "Untitled conversation"}” and its messages will be removed from your account. This cannot be undone.`,
        confirmLabel: "Delete"
      });
      if (!ok) return;
      try {
        const { error } = await sb.from("ai_conversations").delete().eq("id", id);
        if (error) throw error;
        historyRows = historyRows.filter((entry) => entry.id !== id);
        if (conversationId === id) {
          conversationId = null;
          log.innerHTML = emptyState({
            icon: "sparkles",
            title: "Ask anything about the business",
            desc: "That conversation was deleted. Start a new one below."
          });
        }
        paintHistory();
        window.dispatchEvent(new CustomEvent("shinzora:chats-changed"));
        toast({ title: "Conversation deleted" }, { tone: "success" });
      } catch (error) {
        toastError(normalizeError(error));
      }
      return;
    }

    const openButton = event.target.closest("[data-conv]");
    if (!openButton) return;
    await openConversation(openButton.getAttribute("data-conv"));
    paintHistory();
  });

  /* A link from the sidebar arrives here. ?conversation= wins over the "resume
     the last conversation" default, and ?new=1 means exactly that — an empty
     composer rather than somebody else's thread. */
  const params = ctx?.params instanceof URLSearchParams ? ctx.params : new URLSearchParams(location.search);
  const wanted = params.get("conversation");
  if (wanted) {
    const opened = await openConversation(wanted, { updateUrl: false });
    if (!opened) await loadLatestConversation();
  } else if (params.get("new") === "1") {
    startNewConversation({ updateUrl: false });
  } else {
    await loadLatestConversation();
  }

  /* "All chats" from the sidebar opens the same panel the History button does,
     rather than a second, parallel list of conversations. */
  if (params.get("history") === "1") {
    const panel = qs("#history-panel");
    panel.hidden = false;
    await loadHistory();
    panel.scrollIntoView({ behavior: "smooth", block: "nearest" });
  }
}

/** Minimal markdown-ish formatting: code fences, inline code, bold, bullets. */
function formatContent(text = "") {
  const value = String(text);
  const fence = /```([\s\S]*?)```/g;
  let output = esc(value).replace(fence, (_m, code) => `<pre>${esc(code.trim())}</pre>`);
  output = output
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/^\s*[-*]\s+/gm, "• ");
  return output;
}
