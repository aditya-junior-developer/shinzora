/* ==========================================================================
   Shinzora — AI Assistant
   A real conversation against the server-side Gemini proxy. Conversations and
   messages are persisted in Postgres; the browser never sees an API key.
   ========================================================================== */

import { qs, esc, on, safeSet } from "../../../lib/dom.js";
import { icon } from "../../../lib/icons.js";
import { timeAgo } from "../../../lib/format.js";
import { state, aiCredits, plan } from "../../../lib/store.js";
import { sb, normalizeError, getSession } from "../../../lib/supabase.js";
import { api, runtimeConfig } from "../../../lib/api.js";
import { pageHead, emptyState, setupNotice } from "../components.js";
import { toast, toastError } from "../../../ui/toast.js";
import { confirmDialog, formDialog } from "../../../ui/modal.js";

const SUGGESTIONS = [
  "What should my homepage say for a premium fashion label?",
  "Write three Instagram captions for a new ceramic collection.",
  "Review my pricing: 15 products, average order ₹2,400, 22% margin.",
  "Draft a 4-week launch plan for a skincare brand in India.",
  "Which pages does a service business website actually need?"
];

let conversationId = null;

export default async function render(root, ctx) {
  const config = await runtimeConfig();
  const aiReady = Boolean(config?.ai?.configured);

  root.innerHTML = `
    ${pageHead({
      title: "AI Assistant",
      desc: "Ask about strategy, copy, pricing, operations — the assistant sees your business profile as context.",
      actions: `<button class="btn btn-secondary btn-sm" id="new-chat">${icon("plus", { size: 14 })}New conversation</button>
                <span class="badge badge-violet">${icon("sparkles", { size: 11 })}${esc(plan().name)} · ${aiCredits().used}/${aiCredits().limit}</span>`
    })}
    ${!aiReady ? setupNotice({ code: "ai_unconfigured", message: "The AI service is not configured on this deployment.", hint: config?.ai?.key_env ? `Set ${config.ai.key_env} on the server — in .env for a local deployment, or in the project's environment variables — then reload this page. Nothing is simulated while it is missing.` : "Set the AI provider key on the server, then reload this page." }, "The assistant") : ""}
    <div class="chat-shell">
      <div class="chat-head">
        <span class="avatar avatar-sm" style="background:linear-gradient(150deg,#a855f7,#4c1d95)">${icon("sparkles", { size: 13 })}</span>
        <div>
          <div style="font-size:var(--fs-sm);font-weight:600;color:#fff">Shinzora Assistant</div>
          <div class="chat-model">${aiReady ? "Gemini · server-side · conversation saved" : "Offline — service not configured"}</div>
        </div>
        <button class="btn btn-ghost btn-sm" id="history-toggle" style="margin-left:auto">${icon("clock", { size: 14 })}History</button>
      </div>

      <div class="chat-log" id="chat-log">
        ${emptyState({
          icon: "sparkles",
          title: "Ask anything about the business",
          desc: "The assistant answers with your business name, category and goals in context. Every exchange is saved to your account."
        })}
      </div>

      <div class="chat-suggestions" id="chat-suggestions">
        ${SUGGESTIONS.slice(0, 3)
          .map((text) => `<button class="chip" data-suggest="${esc(text)}">${esc(text)}</button>`)
          .join("")}
      </div>

      <div class="chat-composer">
        <div class="composer-box">
          <textarea id="chat-input" rows="1" placeholder="${aiReady ? "Ask the assistant…" : "AI service not configured"}" ${aiReady ? "" : "disabled"} aria-label="Message"></textarea>
          <button class="btn btn-primary btn-sm btn-icon" id="chat-send" ${aiReady ? "" : "disabled"} aria-label="Send message">
            ${icon("send", { size: 15 })}
          </button>
        </div>
        <div class="composer-foot">
          <span>Enter to send · Shift + Enter for a new line</span>
          <span>Responses are generated by AI — verify anything financial or legal.</span>
        </div>
      </div>
    </div>

    <div class="card" id="history-panel" hidden style="margin-top:var(--s-4)">
      <div class="card-head">
        <div class="card-title">Conversations</div>
        <div class="field" style="margin:0;max-width:240px">
          <input class="input input-sm" id="history-search" type="search" placeholder="Search titles" aria-label="Search conversations" />
        </div>
      </div>
      <div class="card-body" id="history-list"><p class="muted" style="font-size:var(--fs-xs)">Loading…</p></div>
    </div>`;

  const log = qs("#chat-log");
  const input = qs("#chat-input");
  const send = qs("#chat-send");

  const scrollDown = () => {
    log.scrollTop = log.scrollHeight;
  };

  const bubble = (role, content, meta = "") => {
    const wrap = document.createElement("div");
    wrap.className = `msg ${role === "user" ? "msg-user" : "msg-ai"}`;
    wrap.innerHTML = `
      <span class="msg-avatar">${role === "user" ? esc((state.profile?.full_name || "You").slice(0, 2).toUpperCase()) : icon("sparkles", { size: 14 })}</span>
      <div>
        <div class="msg-bubble">${formatContent(content)}</div>
        ${meta ? `<div class="msg-meta">${esc(meta)}</div>` : ""}
      </div>`;
    log.append(wrap);
    scrollDown();
    return wrap;
  };

  const thinking = () => {
    const wrap = document.createElement("div");
    wrap.className = "msg msg-ai";
    wrap.setAttribute("data-thinking", "");
    wrap.innerHTML = `<span class="msg-avatar">${icon("sparkles", { size: 14 })}</span>
      <div class="msg-bubble"><span class="typing"><i></i><i></i><i></i></span></div>`;
    log.append(wrap);
    scrollDown();
    return wrap;
  };

  async function loadLatestConversation() {
    try {
      const session = await getSession();
      if (!session) return;
      const { data } = await sb
        .from("ai_conversations")
        .select("id, title, updated_at, user_id")
        .eq("user_id", session.user.id)
        .eq("kind", "assistant")
        .order("updated_at", { ascending: false })
        .limit(1)
        .maybeSingle();
      if (!data) return;
      conversationId = data.id;
      const { data: rows } = await sb
        .from("ai_messages")
        .select("*")
        .eq("conversation_id", data.id)
        .order("created_at", { ascending: true })
        .limit(60);
      if (rows?.length) {
        log.innerHTML = "";
        rows.forEach((row) => bubble(row.role === "user" ? "user" : "ai", row.content, timeAgo(row.created_at)));
      }
    } catch (error) {
      if (normalizeError(error).code !== "schema_missing") console.warn(error);
    }
  }

  async function sendMessage(text) {
    const message = String(text || "").trim();
    if (!message || !aiReady) return;
    if (log.querySelector(".empty")) log.innerHTML = "";
    safeSet("#chat-suggestions", "");

    bubble("user", message, "You");
    input.value = "";
    input.style.height = "auto";
    send.disabled = true;
    const pending = thinking();

    try {
      const result = await api.ai.chat({
        message,
        conversationId,
        context: {
          business: state.business || null,
          plan: plan().id,
          goals: state.business?.goals || []
        }
      });
      pending.remove();
      conversationId = result.conversationId || conversationId;
      bubble("ai", result.reply || "No response was returned.", `${result.model || "gemini"} · saved`);
      if (result.usage) {
        state.subscription = { ...(state.subscription || {}), ai_credits_used: result.usage.used };
        const badge = qs(".page-actions .badge");
        if (badge) badge.innerHTML = `${icon("sparkles", { size: 11 })}${esc(plan().name)} · ${result.usage.used}/${result.usage.limit}`;
      }
    } catch (error) {
      pending.remove();
      const normalized = normalizeError(error);
      if (normalized.code === "functions_unavailable") {
        bubble("ai", `The AI service is not deployed yet.\n\n${normalized.hint || ""}`, "setup required");
      } else {
        bubble("ai", `I could not complete that request.\n\n${normalized.message}${normalized.hint ? `\n\n${normalized.hint}` : ""}`, "error");
      }
      toastError(normalized);
    } finally {
      send.disabled = false;
      input.focus();
    }
  }

  /* ------------------------------------------------------------- listeners */
  on(send, "click", () => sendMessage(input.value));
  on(input, "input", () => {
    input.style.height = "auto";
    input.style.height = `${Math.min(160, input.scrollHeight)}px`;
  });
  on(input, "keydown", (event) => {
    if (event.key === "Enter" && !event.shiftKey) {
      event.preventDefault();
      sendMessage(input.value);
    }
  });
  on(qs("#chat-suggestions"), "click", (event) => {
    const chip = event.target.closest("[data-suggest]");
    if (chip) sendMessage(chip.getAttribute("data-suggest"));
  });
  on(qs("#new-chat"), "click", () => {
    conversationId = null;
    log.innerHTML = emptyState({
      icon: "sparkles",
      title: "New conversation",
      desc: "Ask anything about the business. Context is carried automatically."
    });
    safeSet("#chat-suggestions", SUGGESTIONS.slice(0, 3)
      .map((text) => `<button class="chip" data-suggest="${esc(text)}">${esc(text)}</button>`)
      .join(""));
    input.focus();
  });

  /* ------------------------------------------------------------- history */
  /* Conversations are the user's own record of what the assistant told them.
     The list can be searched, reopened, renamed and deleted, and every state is
     explicit: loading, empty, no matches, or an error with the real reason. */
  let historyRows = [];
  let historyQuery = "";

  function paintHistory() {
    const list = qs("#history-list");
    const term = historyQuery.trim().toLowerCase();
    const rows = term
      ? historyRows.filter((row) => String(row.title || "").toLowerCase().includes(term))
      : historyRows;

    if (!historyRows.length) {
      list.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">No saved conversations yet. Ask something and it is saved automatically.</p>`;
      return;
    }
    if (!rows.length) {
      list.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">No conversation title matches “${esc(historyQuery.trim())}”.</p>`;
      return;
    }

    list.innerHTML = `<div class="version-list">${rows
      .map(
        (row) => `<div class="version-item ${row.id === conversationId ? "is-current" : ""}">
            <button class="vi-main" data-conv="${esc(row.id)}" style="all:unset;display:flex;gap:var(--s-2);align-items:center;flex:1;cursor:pointer;min-width:0">
              <span class="vi-num">${icon("message-square", { size: 12 })}</span>
              <span class="truncate">${esc(row.title || "Untitled conversation")}</span>
            </button>
            <span class="vi-time">${esc(timeAgo(row.updated_at))}</span>
            <button class="btn btn-ghost btn-sm btn-icon" data-rename="${esc(row.id)}" title="Rename" aria-label="Rename conversation">${icon("pencil", { size: 13 })}</button>
            <button class="btn btn-ghost btn-sm btn-icon" data-delete="${esc(row.id)}" title="Delete" aria-label="Delete conversation">${icon("trash-2", { size: 13 })}</button>
          </div>`
      )
      .join("")}</div>`;
  }

  async function loadHistory() {
    const list = qs("#history-list");
    list.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">Loading conversations…</p>`;
    try {
      const session = await getSession();
      if (!session) throw new Error("Sign in again to load your conversations.");
      const { data, error } = await sb
        .from("ai_conversations")
        .select("id, title, updated_at, project_id")
        .eq("user_id", session.user.id)
        .eq("kind", "assistant")
        .order("updated_at", { ascending: false })
        .limit(100);
      if (error) throw error;
      historyRows = data || [];
      paintHistory();
    } catch (error) {
      historyRows = [];
      list.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">${esc(normalizeError(error).message)}</p>`;
    }
  }

  on(qs("#history-toggle"), "click", async () => {
    const panel = qs("#history-panel");
    panel.hidden = !panel.hidden;
    if (!panel.hidden) await loadHistory();
  });

  on(qs("#history-search"), "input", (event) => {
    historyQuery = event.target.value;
    paintHistory();
  });

  on(qs("#history-list"), "click", async (event) => {
    const renameButton = event.target.closest("[data-rename]");
    if (renameButton) {
      const id = renameButton.getAttribute("data-rename");
      const row = historyRows.find((entry) => entry.id === id);
      const values = await formDialog({
        title: "Rename conversation",
        desc: "A short, recognisable title makes the list easy to scan.",
        fields: [{ name: "title", label: "Title", value: row?.title || "", required: true, maxlength: 90 }],
        submitLabel: "Rename",
        size: "sm"
      });
      const next = values?.title;
      if (!next || !next.trim()) return;
      try {
        const { error } = await sb.from("ai_conversations").update({ title: next.trim().slice(0, 90) }).eq("id", id);
        if (error) throw error;
        historyRows = historyRows.map((entry) => (entry.id === id ? { ...entry, title: next.trim().slice(0, 90) } : entry));
        paintHistory();
        toast({ title: "Renamed" }, { tone: "success" });
      } catch (error) {
        toastError(normalizeError(error));
      }
      return;
    }

    const deleteButton = event.target.closest("[data-delete]");
    if (deleteButton) {
      const id = deleteButton.getAttribute("data-delete");
      const row = historyRows.find((entry) => entry.id === id);
      const ok = await confirmDialog({
        title: "Delete this conversation?",
        desc: `“${row?.title || "Untitled conversation"}” and its messages will be removed from your account. This cannot be undone.`,
        confirmLabel: "Delete"
      });
      if (!ok) return;
      try {
        const { error } = await sb.from("ai_conversations").delete().eq("id", id);
        if (error) throw error;
        historyRows = historyRows.filter((entry) => entry.id !== id);
        if (conversationId === id) {
          conversationId = null;
          log.innerHTML = emptyState({
            icon: "sparkles",
            title: "Ask anything about the business",
            desc: "That conversation was deleted. Start a new one below."
          });
        }
        paintHistory();
        toast({ title: "Conversation deleted" }, { tone: "success" });
      } catch (error) {
        toastError(normalizeError(error));
      }
      return;
    }

    const openButton = event.target.closest("[data-conv]");
    if (!openButton) return;
    const id = openButton.getAttribute("data-conv");
    conversationId = id;
    log.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">Loading conversation…</p>`;
    try {
      const { data, error } = await sb
        .from("ai_messages")
        .select("role, content, created_at")
        .eq("conversation_id", id)
        .order("created_at", { ascending: true });
      if (error) throw error;
      log.innerHTML = "";
      (data || []).forEach((row) => bubble(row.role === "user" ? "user" : "ai", row.content, timeAgo(row.created_at)));
      if (!data?.length) {
        log.innerHTML = emptyState({ icon: "message-square", title: "This conversation is empty", desc: "Send a message to start it." });
      }
      paintHistory();
    } catch (error) {
      log.innerHTML = `<p class="muted" style="font-size:var(--fs-xs)">${esc(normalizeError(error).message)}</p>`;
      toastError(normalizeError(error));
    }
  });

  await loadLatestConversation();
  void ctx;
}

/** Minimal markdown-ish formatting: code fences, inline code, bold, bullets. */
function formatContent(text = "") {
  const value = String(text);
  const fence = /```([\s\S]*?)```/g;
  let output = esc(value).replace(fence, (_m, code) => `<pre>${esc(code.trim())}</pre>`);
  output = output
    .replace(/`([^`]+)`/g, "<code>$1</code>")
    .replace(/\*\*([^*]+)\*\*/g, "<strong>$1</strong>")
    .replace(/^\s*[-*]\s+/gm, "• ");
  return output;
}
